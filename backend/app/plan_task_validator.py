"""
plan_task_validator.py
======================
Plan Task Validation and Status Tracking System for BigDream.

This module provides the core logic for decomposing a generated CS learning
plan into discrete, trackable tasks and managing their completion state.

Architecture
------------
A learning plan (generated by plan_generator.py) has the following structure:
  plan.weekly_breakdown = [
    {
      "week": 1,
      "theme": "Python Basics",
      "learning_objectives": ["Understand variables", "Write functions", ...],
      "practice_exercises":  ["Build a calculator", "Complete 10 challenges", ...]
    }, ...
  ]

This module assigns a stable task_id to each objective and exercise, stores
completion state in the goal's database record, and recomputes goal progress
based on actual task completion rather than a fixed formula.

Task ID Format
--------------
  {goal_id}_w{week:02d}_obj_{idx:02d}   (learning objective)
  {goal_id}_w{week:02d}_ex_{idx:02d}    (practice exercise)

Example: "abc12345_w01_obj_00" — goal abc12345, week 1, first objective.

Task Status Enum
----------------
  pending      — not yet started
  in_progress  — user has started this task
  completed    — user marked as complete
  skipped      — user deliberately skipped

Validation Rules
----------------
  - pending     → in_progress | skipped
  - in_progress → completed | pending | skipped
  - completed   → in_progress  (allow un-completing)
  - skipped     → pending
"""

from datetime import datetime
from typing import Dict, List, Optional, Tuple

# ---------------------------------------------------------------------------
# CONSTANTS
# ---------------------------------------------------------------------------
VALID_STATUSES = {"pending", "in_progress", "completed", "skipped"}

ALLOWED_TRANSITIONS: Dict[str, set] = {
    "pending":     {"in_progress", "skipped"},
    "in_progress": {"completed", "pending", "skipped"},
    "completed":   {"in_progress"},
    "skipped":     {"pending"},
}

TASK_WEIGHTS = {
    "objective": 1.0,
    "exercise":  1.5,  # exercises carry slightly more weight (applied learning)
}


# ---------------------------------------------------------------------------
# TASK EXTRACTION
# ---------------------------------------------------------------------------

def extract_tasks_from_plan(goal_id: str, plan: Dict) -> List[Dict]:
    """
    Decompose a generated learning plan into a flat list of trackable tasks.

    Args:
        goal_id: Unique ID of the parent goal.
        plan:    The plan dict from PlanGenerator.generate_plan().

    Returns:
        List of task dicts, each with:
          id, goal_id, week, week_theme, type, text, status, created_at
    """
    tasks = []
    weekly_breakdown = plan.get("weekly_breakdown", [])

    for week_data in weekly_breakdown:
        week_num = week_data.get("week", 0)
        theme = week_data.get("theme", f"Week {week_num}")

        # Learning objectives — use a dense counter so IDs have no gaps
        obj_idx = 0
        for objective in week_data.get("learning_objectives", []):
            if not isinstance(objective, str) or not objective.strip():
                continue
            task_id = f"{goal_id}_w{week_num:02d}_obj_{obj_idx:02d}"
            tasks.append({
                "id": task_id,
                "goal_id": goal_id,
                "week": week_num,
                "week_theme": theme,
                "type": "objective",
                "text": objective.strip(),
                "status": "pending",
                "created_at": datetime.now().isoformat(),
                "completed_at": None,
                "notes": "",
            })
            obj_idx += 1

        # Practice exercises — same dense counter approach
        ex_idx = 0
        for exercise in week_data.get("practice_exercises", []):
            if not isinstance(exercise, str) or not exercise.strip():
                continue
            task_id = f"{goal_id}_w{week_num:02d}_ex_{ex_idx:02d}"
            tasks.append({
                "id": task_id,
                "goal_id": goal_id,
                "week": week_num,
                "week_theme": theme,
                "type": "exercise",
                "text": exercise.strip(),
                "status": "pending",
                "created_at": datetime.now().isoformat(),
                "completed_at": None,
                "notes": "",
            })
            ex_idx += 1

    return tasks


# ---------------------------------------------------------------------------
# STATUS VALIDATION
# ---------------------------------------------------------------------------

def validate_status_transition(current_status: str, new_status: str) -> Tuple[bool, str]:
    """
    Validate whether a status transition is allowed.

    Returns:
        (is_valid: bool, error_message: str)
        error_message is empty string if valid.
    """
    if new_status not in VALID_STATUSES:
        return False, f"Invalid status '{new_status}'. Must be one of: {sorted(VALID_STATUSES)}"

    if current_status not in ALLOWED_TRANSITIONS:
        return False, f"Unknown current status '{current_status}'"

    if new_status not in ALLOWED_TRANSITIONS[current_status]:
        allowed = sorted(ALLOWED_TRANSITIONS[current_status])
        return False, (
            f"Cannot transition from '{current_status}' to '{new_status}'. "
            f"Allowed transitions: {allowed}"
        )

    return True, ""


# ---------------------------------------------------------------------------
# PROGRESS COMPUTATION
# ---------------------------------------------------------------------------

def compute_task_progress(tasks: List[Dict]) -> Dict:
    """
    Compute progress statistics from a list of tasks.

    Returns a dict with:
      total_tasks, completed_tasks, in_progress_tasks,
      skipped_tasks, pending_tasks,
      completion_rate (0.0 – 1.0),
      weighted_completion_rate (0.0 – 1.0),
      by_week: {week_num: {total, completed, rate}}
    """
    if not tasks:
        return {
            "total_tasks": 0,
            "completed_tasks": 0,
            "in_progress_tasks": 0,
            "skipped_tasks": 0,
            "pending_tasks": 0,
            "completion_rate": 0.0,
            "weighted_completion_rate": 0.0,
            "by_week": {},
        }

    counts = {"pending": 0, "in_progress": 0, "completed": 0, "skipped": 0}
    total_weight = 0.0
    completed_weight = 0.0
    by_week: Dict[int, Dict] = {}

    for task in tasks:
        status = task.get("status", "pending")
        task_type = task.get("type", "objective")
        week = task.get("week", 0)
        weight = TASK_WEIGHTS.get(task_type, 1.0)

        counts[status] = counts.get(status, 0) + 1
        total_weight += weight
        if status == "completed":
            completed_weight += weight

        if week not in by_week:
            by_week[week] = {"total": 0, "completed": 0, "in_progress": 0,
                             "theme": task.get("week_theme", f"Week {week}")}
        by_week[week]["total"] += 1
        if status == "completed":
            by_week[week]["completed"] += 1
        if status == "in_progress":
            by_week[week]["in_progress"] += 1

    total = len(tasks)
    for week_data in by_week.values():
        week_data["completion_rate"] = round(
            week_data["completed"] / week_data["total"], 4
        ) if week_data["total"] > 0 else 0.0

    return {
        "total_tasks": total,
        "completed_tasks": counts["completed"],
        "in_progress_tasks": counts["in_progress"],
        "skipped_tasks": counts["skipped"],
        "pending_tasks": counts["pending"],
        "completion_rate": round(counts["completed"] / total, 4) if total > 0 else 0.0,
        "weighted_completion_rate": round(completed_weight / total_weight, 4) if total_weight > 0 else 0.0,
        "by_week": by_week,
    }


def get_current_week(tasks: List[Dict]) -> int:
    """
    Determine the user's current recommended week based on task completion.
    Returns the first week with incomplete tasks, or the last week if all done.
    """
    if not tasks:
        return 1

    weeks_completed = set()
    all_weeks = set()

    for task in tasks:
        week = task.get("week", 1)
        all_weeks.add(week)
        if task.get("status") == "completed":
            weeks_completed.add(week)

    # Find first week where not all tasks are complete
    for week in sorted(all_weeks):
        week_tasks = [t for t in tasks if t.get("week") == week]
        all_complete = all(t.get("status") == "completed" for t in week_tasks)
        if not all_complete:
            return week

    return max(all_weeks) if all_weeks else 1


# ---------------------------------------------------------------------------
# TASK FILTERING HELPERS
# ---------------------------------------------------------------------------

def get_tasks_for_week(tasks: List[Dict], week: int) -> List[Dict]:
    """Filter tasks for a specific week."""
    return [t for t in tasks if t.get("week") == week]


def get_tasks_by_status(tasks: List[Dict], status: str) -> List[Dict]:
    """Filter tasks by status."""
    return [t for t in tasks if t.get("status") == status]


def get_overdue_tasks(tasks: List[Dict], current_week: int) -> List[Dict]:
    """
    Return tasks from weeks before current_week that are not completed.
    These represent falling-behind indicators.
    """
    return [
        t for t in tasks
        if t.get("week", 0) < current_week
        and t.get("status") not in ("completed", "skipped")
    ]


# ---------------------------------------------------------------------------
# TASK MERGE (for existing goals that pre-date task tracking)
# ---------------------------------------------------------------------------

def merge_existing_completions(
    extracted_tasks: List[Dict],
    stored_completions: Dict[str, Dict]
) -> List[Dict]:
    """
    Merge freshly-extracted tasks with previously stored completion data.
    This allows the plan to be re-extracted without losing progress.

    Args:
        extracted_tasks:   Tasks from extract_tasks_from_plan().
        stored_completions: {task_id: {status, completed_at, notes}} from DB.

    Returns:
        Tasks with stored completion data applied.
    """
    merged = []
    for task in extracted_tasks:
        task_id = task["id"]
        stored = stored_completions.get(task_id, {})
        if stored:
            task["status"] = stored.get("status", task["status"])
            task["completed_at"] = stored.get("completed_at")
            task["notes"] = stored.get("notes", "")
        merged.append(task)
    return merged


# ---------------------------------------------------------------------------
# PLAN VALIDATION REPORT
# ---------------------------------------------------------------------------

def generate_validation_report(goal: Dict, tasks: List[Dict]) -> Dict:
    """
    Generate a comprehensive validation report for a goal's plan progress.

    Returns a structured dict suitable for the API response and the
    evaluation framework.
    """
    progress = compute_task_progress(tasks)
    current_week = get_current_week(tasks)
    overdue = get_overdue_tasks(tasks, current_week)

    total_weeks = goal.get("total_weeks", 8)
    goal_type = goal.get("goal_type", "coding")

    # Derive plan health status
    weighted_rate = progress["weighted_completion_rate"]
    if weighted_rate >= 0.9:
        health = "excellent"
    elif weighted_rate >= 0.7:
        health = "on_track"
    elif weighted_rate >= 0.4:
        health = "needs_attention"
    else:
        health = "at_risk"

    # Recommendations based on health
    recommendations = []
    if overdue:
        recommendations.append(
            f"You have {len(overdue)} overdue task(s) from week(s) before {current_week}. "
            "Consider revisiting them before advancing."
        )
    if progress["in_progress_tasks"] == 0 and progress["pending_tasks"] > 0:
        recommendations.append(
            "No tasks are currently in progress. Pick a task from the current week to start."
        )
    if health == "at_risk":
        recommendations.append(
            "Your progress is significantly behind plan. "
            "Consider breaking tasks into smaller daily steps."
        )

    return {
        "goal_id": goal.get("id", ""),
        "goal_title": goal.get("title", ""),
        "goal_type": goal_type,
        "total_weeks": total_weeks,
        "current_week": current_week,
        "plan_health": health,
        "progress": progress,
        "overdue_task_count": len(overdue),
        "recommendations": recommendations,
        "generated_at": datetime.now().isoformat(),
    }
